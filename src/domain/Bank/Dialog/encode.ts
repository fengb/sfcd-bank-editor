import { chunk, mapValues, sumBy } from 'es-toolkit'

import { CHAR_TO_TOKEN, OFFSET } from './decode'

export function packBits(bits: number[]): Uint8Array {
  const bytes = new Uint8Array((bits.length + 7) >> 3)
  bits.forEach((bit, i) => {
    if (bit) bytes[i >> 3]! |= 1 << (7 - (i & 7))
  })
  return bytes
}

function concatBytes(chunks: Uint8Array[]): Uint8Array {
  const total = sumBy(chunks, (chunk) => chunk.length)
  const out = new Uint8Array(total)
  let cursor = 0
  for (const c of chunks) {
    out.set(c, cursor)
    cursor += c.length
  }
  return out
}

type TreeNode = { freq: number; token: number } | { freq: number; left: TreeNode; right: TreeNode }

type TreeNodes = Record<number, TreeNode>

function pathBits(node: TreeNode, token: number): number[] | null {
  if ('token' in node) {
    return node.token === token ? [] : null
  }
  const left = pathBits(node.left, token)
  if (left !== null) return [0, ...left]
  const right = pathBits(node.right, token)
  if (right !== null) return [1, ...right]
  return null
}

export function stringToTokens(str: string): number[] {
  const tokens: number[] = []
  for (let i = 0; i < str.length; i++) {
    const char = str[i]!
    const token = CHAR_TO_TOKEN[char]
    if (token === undefined) throw new Error(`unknown character: ${char}`)
    tokens.push(token)

    if (char === 'Ⓝ' || char === 'ⓒ') {
      const next = str[++i]!
      const value = parseInt(next, 16)
      if (Number.isNaN(value)) throw new Error('prefix token without hex value')
      tokens.push(value)
    }
  }
  return tokens
}

export function encodeTokens(treeNodes: TreeNodes, tokens: number[]): Uint8Array {
  let prev = 0xfe
  const bits = [...tokens, 0xfe].flatMap((token) => {
    const tree = treeNodes[prev]
    if (!tree) throw new Error(`missing tree for 0x${prev.toString(16)}`)
    prev = token

    const path = pathBits(tree, token)
    if (path === null)
      throw new Error(`token 0x${token.toString(16)} not encodable in current tree`)
    return path
  })

  return packBits(bits)
}

export function encodeDialogPage(treeNodes: TreeNodes, tokenLists: number[][]): Uint8Array {
  const chunks: number[] = []
  for (const tl of tokenLists) {
    const b = encodeTokens(treeNodes, tl)
    if (b.length > 255) throw new Error('encoded string too long for page')
    chunks.push(b.length, ...b)
  }
  chunks.push(0) // Terminate the page bytes
  return new Uint8Array(chunks)
}

function buildHuffmanTree(frequencies: Map<number, number>): TreeNode {
  const nodes: TreeNode[] = [...frequencies.entries()].map(([token, freq]) => ({ token, freq }))
  if (nodes.length === 0) throw new Error('cannot build tree with no symbols')
  while (nodes.length > 1) {
    nodes.sort((a, b) => a.freq - b.freq)
    const a = nodes.shift()!
    const b = nodes.shift()!
    nodes.push({ freq: a.freq + b.freq, left: a, right: b })
  }
  return nodes[0]!
}

function serializeTreeNode(node: TreeNode): { bytes: Uint8Array; leafCount: number } {
  const bits: number[] = []
  const leaves: number[] = []
  function dfs(n: TreeNode): void {
    if ('token' in n) {
      bits.push(1)
      leaves.push(n.token)
      return
    }
    bits.push(0)
    dfs(n.left)
    dfs(n.right)
  }
  dfs(node)
  const leafCount = leaves.length
  const treeBytes = packBits(bits)
  const out = new Uint8Array(leafCount + treeBytes.length)
  out.set(leaves.reverse(), 0)
  out.set(treeBytes, leafCount)
  return { bytes: out, leafCount }
}

function buildDialogTrees(tokenLists: number[][]): TreeNodes {
  const transitions: Record<number, Map<number, number>> = {}

  for (const tl of tokenLists) {
    let current = 0xfe
    for (const token of [...tl, 0xfe]) {
      const frequencies = (transitions[current] = transitions[current] ?? new Map<number, number>())
      frequencies.set(token, (frequencies.get(token) ?? 0) + 1)
      current = token
    }
  }

  return mapValues(transitions, buildHuffmanTree)
}

