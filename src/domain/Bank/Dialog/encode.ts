export function encodeDialog(strings: string[]): Uint8Array {
  const tokenLists = strings.map(stringToTokens)
  const treeNodes = buildDialogTrees(tokenLists)
  const pages = chunk(tokenLists, 256).map((p) => encodeDialogPage(treeNodes, p))

  const offsets: number[] = new Array(255).fill(0xffff)
  const treeChunks: Uint8Array[] = []
  let treeDataCursor = 0
  for (let token = 0; token < 255; token++) {
    const treeNode = treeNodes[token]
    if (!treeNode) continue
    const serialized = serializeTreeNode(treeNode)
    offsets[token] = treeDataCursor + serialized.leafCount
    treeChunks.push(serialized.bytes)
    treeDataCursor += serialized.bytes.length
  }
  const treeDataBytes = concatBytes(treeChunks)
  const offsetTableOffset = DIALOG_HEADER_PREFIX.length
  const offsetTableBytes = 255 * 2
  const treeDataOffset = offsetTableOffset + offsetTableBytes
  const pageRegionOffset = treeDataOffset + treeDataBytes.length
  let pCursor = pageRegionOffset
  const pageStarts: number[] = []
  for (const pb of pages) {
    pageStarts.push(pCursor)
    pCursor += pb.length
  }
  const pageRegionBytes = concatBytes(pages)
  const pointerTableOffset = pageRegionOffset + pageRegionBytes.length
  const total = pointerTableOffset + pages.length * 4
  const out = new Uint8Array(total)
  out.set(DIALOG_HEADER_PREFIX, 0)
  const view = new DataView(out.buffer)
  for (let i = 0; i < 255; i++) {
    view.setUint16(offsetTableOffset + i * 2, offsets[i]!)
  }
  out.set(treeDataBytes, treeDataOffset)
  out.set(pageRegionBytes, pageRegionOffset)
  for (let i = 0; i < pageStarts.length; i++) {
    view.setUint32(pointerTableOffset + i * 4, OFFSET + pageStarts[i]!)
  }
  view.setUint32(0x00, OFFSET + pointerTableOffset)
  view.setUint32(0x40, OFFSET + offsetTableOffset)
  view.setUint32(0x4a, OFFSET + treeDataOffset)
  return out
}
